package runner

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func (r *BenchRunner) writeStaticDocs() error {
	files := map[string]string{
		r.paths.Readme:      r.readmeTemplate(),
		r.paths.Environment: r.environmentTemplate(),
		r.paths.Summary:     r.summaryTemplate(),
		r.paths.Report:      r.reportTemplate(),
		r.paths.Comparison:  r.comparisonTemplate(),
		r.paths.Feasibility: r.feasibilityTemplate(),
	}
	for path, content := range files {
		if err := seedStaticFile(path, content); err != nil {
			return err
		}
	}
	return r.syncAnalysisBundle()
}

func seedStaticFile(path string, content string) error {
	if fileExists(path) {
		return nil
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

func (r *BenchRunner) syncAnalysisBundle() error {
	sourceDir := filepath.Join(r.opts.RootDir, "python-loader", "go-server", "benchmark", "analysis")
	entries, err := os.ReadDir(sourceDir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		sourcePath := filepath.Join(sourceDir, entry.Name())
		targetPath := filepath.Join(r.paths.AnalysisDir, entry.Name())
		data, err := os.ReadFile(sourcePath)
		if err != nil {
			return err
		}
		if err := os.WriteFile(targetPath, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

