def write_feasibility(root: Path) -> None:
    (root / "diskann_label_feasibility.md").write_text("""# DiskANN Label Filtering Feasibility

## Status

Not evaluated in this Phase F v2 pilot run. The file is retained as the placeholder required by the global experiment tree layout.

## Current Boundary

- exp5-exp8 compare available index/query behavior on `pilot_94k`.
- No label-filtering prototype result is claimed in this tree.
- Any future DiskANN label-filtering claim must include explicit label mapping, update cost, multi-label semantics, and prototype measurements.
""")


def format_counter(counter: Counter[str]) -> str:
    return ", ".join(f"`{key}`={counter[key]}" for key in sorted(counter))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--pair", required=True, type=Path)
    parser.add_argument("--role", required=True, choices=["main", "audit"])
    parser.add_argument("--dataset", default="pilot_94k")
    args = parser.parse_args()
    counts = csv_line_counts(args.root)
    write_readme(args.root, args)
    write_summary(args.root, args, counts)
    write_report(args.root, args, counts)
    write_comparison(args.root, args, counts)
    write_environment(args.root, args)
    write_feasibility(args.root)


if __name__ == "__main__":
    main()
