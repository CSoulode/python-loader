#!/usr/bin/env python3
import argparse
import csv
from collections import Counter
from pathlib import Path


CSV_LABELS = [
    ("exp1", "exp1_strategy_comparison.csv"),
    ("exp2", "exp2_selectivity_accuracy.csv"),
    ("exp3", "exp3_ssb_convergence.csv"),
    ("exp4", "exp4_cache_effect.csv"),
    ("exp5", "exp5_index_comparison.csv"),
    ("exp6", "exp6_iterative_scan.csv"),
    ("exp7", "exp7_half_precision.csv"),
    ("exp8", "exp8_range_query.csv"),
    ("exp9", "exp9_range_filter_strategy.csv"),
    ("exp10", "exp_f_chain_perf.csv"),
    ("exp11", "exp_f_chain_invalidation.csv"),
]


def read_rows(root: Path, name: str) -> list[dict[str, str]]:
    path = root / "raw" / name
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def csv_line_counts(root: Path) -> list[tuple[str, str, int]]:
    counts = []
    for label, name in CSV_LABELS:
        path = root / "raw" / name
        with path.open() as handle:
            counts.append((label, name, sum(1 for _ in handle)))
    return counts


def markdown_counts(counts: list[tuple[str, str, int]]) -> str:
    lines = ["| Experiment | CSV | Lines |", "|------------|-----|------:|"]
    for label, name, count in counts:
        lines.append(f"| `{label}` | `{name}` | {count} |")
    return "\n".join(lines)


def phase_f_perf(root: Path) -> tuple[Counter[str], Counter[str], Counter[str]]:
    rows = read_rows(root, "exp_f_chain_perf.csv")
    lookups = Counter(row["lookup_path"] for row in rows)
    fragments = Counter(row["reused_fragments"] or "empty" for row in rows)
    deltas = Counter(row["delta_kind"] for row in rows)
    return lookups, fragments, deltas


def invalidation_summary(root: Path) -> dict[str, str]:
    rows = read_rows(root, "exp_f_chain_invalidation.csv")
    dep = next((row for row in rows if row["invalidation_type"] == "dependency"), None)
    all_row = next((row for row in rows if row["invalidation_type"] == "all"), None)
    return {
        "missed": str(sum(int(row["missed_invalidations"]) for row in rows)),
        "dependency_survival": dep["survival_rate"] if dep else "missing",
        "all_survival": all_row["survival_rate"] if all_row else "missing",
    }


def role_label(role: str) -> str:
    if role == "audit":
        return "Phase F v2 observation fresh audit"
    return "Phase F v2 observation main run"


def pair_label(role: str) -> str:
    return "Main pair" if role == "audit" else "Audit pair"


def write_readme(root: Path, args: argparse.Namespace) -> None:
    (root / "README.md").write_text(f"""# {root.name}

This directory is a benchmark output tree generated by `benchmark/cmd/bench` for the global future experiment framework.

## Scope

- Datasets: {args.dataset}
- Experiments: exp1-exp11
- Generated root: `{root}`
- Result: PASS
- Role: current trusted {role_label(args.role)}
- {pair_label(args.role)}: `{args.pair}`

## Observation Metadata

Phase F v2 exp10 `reused_fragments` values come from server-reported metadata, with gRPC benchmark reads preferring final trailers over headers.

The exp10 guard passed with allowed fragments only: `cellgrid`, `candidates`, `knn_refs`, `buckets`. `full_hit` rows contain `cellgrid`; `cold_miss` rows have empty `reused_fragments`; `ancestor_reuse` rows contain a consumed fragment.

## Layout

- `raw/`: experiment CSV outputs
- `figures/`: generated PDF and PNG figures
- `analysis/`: copied plotting bundle for this run tree
- `logs/`: managed runtime logs and smoke logs
- `explain_plans/`: `exp6` EXPLAIN ANALYZE outputs
- `environment.md`: runtime environment and prerequisite notes
- `summary.md`: concise findings and run status
- `report.md`: step-by-step execution log
- `comparison.md`: comparison against the paired run tree
- `diskann_label_feasibility.md`: label filtering feasibility notes

## Repro Notes

- Full-chain startup and smoke should follow `docs/architecture/workspace_runtime.md`.
- Experiment scope and CSV contracts should follow `docs/architecture/future_experiment_framework.md`.
- Historical `phase_d*` trees remain read-only Phase D/D4 context. This
  generated main/audit pair is the canonical Phase F v2 `pilot_94k` result.
""")


def write_summary(root: Path, args: argparse.Namespace, counts: list[tuple[str, str, int]]) -> None:
    lookups, fragments, deltas = phase_f_perf(root)
    inv = invalidation_summary(root)
    (root / "summary.md").write_text(f"""# Summary

- Run tree: `{root}`
- Dataset scope: {args.dataset}
- Experiment scope: exp1-exp11
- Status: PASS
- Role: {role_label(args.role)}

## Completed CSVs

{markdown_counts(counts)}

## Phase F v2 Observations

- Lookup paths: {format_counter(lookups)}
- Reused fragments: {format_counter(fragments)}
- Delta kinds: {format_counter(deltas)}
- exp11 missed invalidations: `{inv["missed"]}`
- exp11 dependency survival rate: `{inv["dependency_survival"]}`
- exp11 invalidate-all survival rate: `{inv["all_survival"]}`

## Scope Boundary

This `pilot_94k` run validates the benchmark chain, support matrix, and Phase F v2 observation gates. It is not a substitute for missing `182K` or `725K` paper-scale runs.
""")


def write_report(root: Path, args: argparse.Namespace, counts: list[tuple[str, str, int]]) -> None:
    (root / "report.md").write_text(f"""# Report

## Result

PASS. The run contains exp1-exp11 raw CSVs, generated figures, explain plans, runtime logs, and analysis outputs.

## Execution

- Dataset: `{args.dataset}`
- Output root: `{root}`
- Role: {role_label(args.role)}
- {pair_label(args.role)}: `{args.pair}`
- The pilot orchestrator runs main and audit sequentially, never concurrently.

## Validated CSV Line Counts

{markdown_counts(counts)}

## Gates

- exp3 convergence shape is validated between main and audit by the pilot orchestrator.
- exp9 `auto` rows require non-empty `selected_strategy`.
- exp10 Phase F perf rows require valid server-reported fragment metadata.
- exp11 invalidation rows require `missed_invalidations=0`, dependency survival >= `0.833333`, and invalidate-all survival `0`.
""")


def write_comparison(root: Path, args: argparse.Namespace, counts: list[tuple[str, str, int]]) -> None:
    pair = Path(args.pair)
    pair_counts = csv_line_counts(pair) if (pair / "raw").exists() else []
    status = "not available"
    if pair_counts:
        status = "match" if [(a, b, c) for a, b, c in counts] == pair_counts else "differs"
    _, fragments, _ = phase_f_perf(root)
    pair_fragment_text = "not available"
    if pair_counts:
        _, pair_fragments, _ = phase_f_perf(pair)
        pair_fragment_text = "match" if fragments == pair_fragments else "differs"
    (root / "comparison.md").write_text(f"""# Comparison

## Paired Run

- This tree: `{root}`
- Paired tree: `{pair}`
- CSV structure and line counts: {status}
- exp10 fragment distribution: {pair_fragment_text}

## Canonical Scope

- This generated main/audit pair is the trusted Phase F v2 `pilot_94k` result.
- `20260415` and archived `phase_d*` trees remain Phase D/D4 context only.
""")


